def log_blocks(name):
    """Лог s51 -> список (команда, [строки вывода])."""
    out, cur = [], None
    for ln in read(f"sim/{name}").splitlines():
        if ln.startswith("s51> "):
            cur = (ln[5:], [])
            out.append(cur)
        elif cur is not None:
            cur[1].append(ln)
    return out


def excerpt(name, picks):
    """picks: [(префикс команды, как обрезать: None | ('head', n) | ('ends', n, m) | ('grep', подстрока...))]."""
    blocks = log_blocks(name)
    res = []
    for pick in picks:
        prefix, how = pick[:2]
        idx = pick[2] if len(pick) > 2 else -1
        blk = [b for b in blocks if b[0].startswith(prefix)][idx]
        cmd, lines = blk
        if how:
            if how[0] == "head":
                lines = lines[:how[1]]
            elif how[0] == "ends":
                lines = lines[:how[1]] + ["..."] + lines[-how[2]:]
            elif how[0] == "grep":
                lines = [l for l in lines if any(g in l for g in how[1:])]
        res.append(f"s51> {cmd}")
        res += [l.rstrip() for l in lines]
    return "\n".join(res)


def ihx_bytes(path):
    n = 0
    for ln in open(os.path.join(HERE, path)):
        if ln.startswith(":") and ln[7:9] == "00":
            n += int(ln[1:3], 16)
    return n


