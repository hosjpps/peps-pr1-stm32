def ev_rows(events, limit):
    rows = []
    for e in events[:limit]:
        k = e["kind"]
        if k in ("S", "Sr", "P"):
            rows.append([f"{e['t']:.0f}", {"S": "START", "Sr": "повторный START", "P": "STOP"}[k], "—", "—"])
        elif k == "addr":
            rows.append([f"{e['t']:.0f}", f"SLA+{'R' if e['read'] else 'W'}", f"0x{e['value']:02X}",
                         "ACK" if e["ack"] else "NACK"])
        else:
            rows.append([f"{e['t']:.0f}", "данные (чтение)" if e["read"] else "данные (запись)",
                         f"0x{e['value']:02X}", "ACK" if e["ack"] else "NACK"])
    return rows


